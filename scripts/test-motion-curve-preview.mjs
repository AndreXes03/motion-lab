import assert from 'node:assert/strict';
import {sourceCurvePoints, sourceTimingKeys, sampleSourceChannel} from '../src/engine/motion-curve-preview.js';
import {sampleAnimationGroupTime} from '../src/engine/animation-groups.js';
const native = {source:'keys', keys:[{t:0,value:0,ease:'smooth'},{t:1,value:4,ease:'out'},{t:2,value:1,ease:'linear'}]};
const window = {start:0,end:2};
const keys = sourceTimingKeys(native, window);
assert.deepEqual(keys.map(k=>k.t),[0,1,2]);
const animation = {version:1, enabled:true, groups:{camera:{...window,rate:1,keys}}};
const untouched = JSON.stringify(native);
const before = sourceCurvePoints(native, window), identity = sourceCurvePoints(native,{...window,animation,groupId:'camera'});
assert.deepEqual(identity,before);
animation.groups.camera.keys[1].t=1.5;
const retimed = sourceCurvePoints(native,{...window,animation,groupId:'camera'});
for (const point of retimed.slice(0,-1)) assert.equal(point.value,sampleSourceChannel(native,sampleAnimationGroupTime({animation},'camera',point.t)));
assert.equal(sampleSourceChannel(native,sampleAnimationGroupTime({animation},'camera',1.5)),4);
assert.equal(JSON.stringify(native),untouched);
const observed = {source:'samples',keys:[{t:0,value:0,ease:'smooth'},{t:2,value:4,ease:'smooth'}]};
assert.equal(sampleSourceChannel(observed,.5),1);
assert.equal(sourceTimingKeys(observed,window).length,5);
console.log('Source curve preview: original easing, identity, retiming and observed interpolation verified.');
