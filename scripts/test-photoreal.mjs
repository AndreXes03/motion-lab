import assert from 'node:assert/strict';
import * as T from 'three';
import { freezeScene } from '../experiments/photoreal/scene.js';

const texture = new T.Texture();
const material = new T.MeshPhysicalMaterial({ clearcoat: .8, metalness: .7, roughness: .3, map: texture });
const geometry = new T.BoxGeometry(1, 1, 1);
const root = new T.Group();
root.position.set(3, 0, 0);
const instances = new T.InstancedMesh(geometry, material, 2);
instances.setMatrixAt(0, new T.Matrix4().makeTranslation(0, 1, 0));
instances.setMatrixAt(1, new T.Matrix4().makeTranslation(2, 1, 0));
root.add(instances);
const hidden = new T.Mesh(geometry, material);
hidden.visible = false;
root.add(hidden);
let sourceDisposals = 0;
for (const value of [geometry, material, texture]) value.addEventListener('dispose', () => sourceDisposals++);
const frozen = freezeScene(root);
assert.equal(frozen.root.children.length, 2);
assert.equal(frozen.report.instances, 2);
assert.equal(frozen.report.triangles, 24);
assert.equal(frozen.report.disabledClearcoat, 1);
assert.equal(material.clearcoat, .8, 'source coating must remain intact');
assert.equal(frozen.root.children[0].material.clearcoat, 0);
assert.equal(frozen.root.children[0].material.map, texture, 'snapshot borrows texture');
assert.notEqual(frozen.root.children[0].geometry, geometry);
const bounds = new T.Box3().setFromObject(frozen.root);
assert.deepEqual(bounds.min.toArray(), [2.5, .5, -.5]);
assert.deepEqual(bounds.max.toArray(), [5.5, 1.5, .5]);
frozen.dispose();
assert.equal(sourceDisposals, 0, 'snapshot disposal must not dispose source assets');

const basic = new T.MeshBasicMaterial({ color: '#ff8800', transparent: true, opacity: .4 });
const adapted = freezeScene(new T.Mesh(geometry, basic));
assert.equal(adapted.report.basicMaterials, 1);
assert.equal(adapted.root.children[0].material.opacity, .4);
assert.equal(adapted.root.children[0].material.color.getHex(), basic.color.getHex());
adapted.dispose();
assert.throws(() => freezeScene(new T.Mesh(geometry, new T.ShaderMaterial())), /Unsupported material/);
console.log('Photoreal snapshot checks passed: transforms, instances, material adaptation, ownership, unsupported types.');
