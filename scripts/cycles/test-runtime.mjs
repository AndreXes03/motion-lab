import assert from 'node:assert/strict';
import {mkdtemp,writeFile,chmod,mkdir,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {findBlender,getCyclesCapabilities} from './studio.mjs';
import {normalizeCyclesOptions} from './options.mjs';
const temp=await mkdtemp(path.join(os.tmpdir(),'cycles-runtime-'));
try{
 const fake=path.join(temp,'blender');
 await writeFile(fake,'#!/bin/sh\nexit 0\n');await chmod(fake,0o755);
 assert.equal(await findBlender('blender',{env:{PATH:temp}}),fake);
 assert.equal(await findBlender(undefined,{env:{PATH:temp}}),fake);
 await mkdir(path.join(temp,'directory'));
 await assert.rejects(findBlender(path.join(temp,'directory')),/unavailable/);
 if(process.platform!=='win32'){
  await chmod(fake,0o644);await assert.rejects(findBlender(fake),/not executable/);await chmod(fake,0o755);
  // Malformed probe output must become an unavailable result, not an uncaught exception.
  await writeFile(fake,"#!/bin/sh\nprintf 'MOTION_CYCLES invalid-json\\n'\n");
  assert.equal((await getCyclesCapabilities({blenderPath:fake})).available,false);
  await writeFile(fake,`#!/bin/sh\nprintf '%s\\n' 'MOTION_CYCLES {"version":"test","devices":[{"type":"CUDA","name":"Test GPU"}]}'\n`);
  const caps=await getCyclesCapabilities({blenderPath:fake});assert.equal(caps.available,true);assert.equal(caps.device,'CUDA');assert.deepEqual(caps.scenes,['pulse']);
  await writeFile(fake,"#!/bin/sh\nprintf 'Python script failed\\n'\nexit 1\n");
  assert.equal((await getCyclesCapabilities({blenderPath:fake})).available,false);
 }
 assert.equal(normalizeCyclesOptions({command:'frame',time:13.9,start:13.9}).count,1);
 assert.equal(normalizeCyclesOptions({command:'frame'},{start:0,end:0}).duration,0);
 assert.equal(normalizeCyclesOptions({},{settings:{workers:'auto'}}).workers,1);
 assert.equal(normalizeCyclesOptions({},{settings:{audio:'/tmp/sound.wav'}}).audio,'/tmp/sound.wav');
 assert.throws(()=>normalizeCyclesOptions({command:'export',start:13.9}),/duration/);
 console.log('Cycles PATH/executable discovery, robust capability probe and snapshot restoration passed');
}finally{await rm(temp,{recursive:true,force:true});}
const {sourceDigest,isSourceArtifact}=await import('./cache.mjs');
const source=await mkdtemp(path.join(os.tmpdir(),'cycles-source-'));
try{
 await mkdir(path.join(source,'scripts/cycles'),{recursive:true});
 for(const file of ['package.json','package-lock.json','scripts/cycles.mjs','scripts/music-assets.mjs','scripts/cycles/devices.py'])await writeFile(path.join(source,file),'source');
 const first=await sourceDigest(source);
 await mkdir(path.join(source,'scripts/cycles/__pycache__'));
 await writeFile(path.join(source,'scripts/cycles/__pycache__/devices.cpython.pyc'),'generated');
 await writeFile(path.join(source,'scripts/cycles/progressive.pyc'),'generated');
 assert.equal(await sourceDigest(source),first,'Generated Python bytecode must not break resume');
 assert.equal(isSourceArtifact(path.join(source,'scripts/cycles/__pycache__')),false);
 assert.equal(isSourceArtifact(path.join(source,'project/references/music')),false,'Freeze only the selected song separately');
 await writeFile(path.join(source,'scripts/cycles/devices.py'),'modified');
 assert.notEqual(await sourceDigest(source),first,'Changed adapter source must invalidate resume');
 console.log('Cycles source fingerprint excludes generated bytecode and detects real source changes');
}finally{await rm(source,{recursive:true,force:true});}
